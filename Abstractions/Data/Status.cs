/// <summary>
/// Playback status of Winamp
/// </summary>
public enum Status {

    /// <summary>
    /// Winamp is stopped or exited
    /// </summary>
    Stopped,

    /// <summary>
    /// Winamp is playing
    /// </summary>
    Playing,

    /// <summary>
    /// Winamp is paused
    /// </summary>
    Paused

}